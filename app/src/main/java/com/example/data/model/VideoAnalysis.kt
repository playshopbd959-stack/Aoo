package com.example.data.model

import androidx.room.Entity
import androidx.room.PrimaryKey

data class RetentionPoint(
    val second: Int,
    val retentionPercent: Int,
    val note: String? = null
)

data class PersonaSimulation(
    val persona: String,
    val sentiment: String,
    val score: Int,
    val expectedCompletion: Int,
    val behavioralFeedback: String
)

data class TitleVariation(
    val concept: String,
    val predictedCtrLift: String,
    val rationale: String
)

data class RecommendationItem(
    val category: String, // "INTRO", "TITLE", "THUMBNAIL", "SEO"
    val urgency: String, // "HIGH", "MEDIUM", "LOW"
    val actionText: String
)

@Entity(tableName = "video_analyses")
data class VideoAnalysisEntity(
    @PrimaryKey
    val id: String, // video ID e.g. "dQw4w9WgXcQ"
    val originalUrl: String,
    val title: String,
    val channelTitle: String,
    val thumbnailUrl: String,
    val isVerifiedApiData: Boolean = false, // true = verified via official API or oEmbed
    val viewCount: Long = 0,
    val likeCount: Long = 0,
    val commentCount: Long = 0,
    val durationText: String = "--:--",
    val durationSeconds: Int = 0,
    
    // Real analytical metrics generated by agent clusters
    val titleAnalysisScore: Int = 85,
    val titleFeedback: String = "Title length is optimal for mobile displays.",
    val descriptionAnalysisScore: Int = 78,
    val descriptionFeedback: String = "Good keyword density; lacks chapter timestamps.",
    val introPacingScore: Int = 82,
    val introWeakPointWarning: String? = null,
    
    val retentionJson: String = "",       // JSON / serialized retention curve points
    val personasJson: String = "",        // Persona reactions
    val recommendationsJson: String = "", // List of actionable recommendations
    val abVariationsJson: String = "",    // Title / Thumbnail variations
    val summaryReport: String = "",
    val analyzedAt: Long = System.currentTimeMillis()
)
